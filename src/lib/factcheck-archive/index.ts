/**
 * Verifact's archive of Romanian-language fact-checks: every verdict published
 * by Factual.ro, AFP Verificat, Lead Stories România, BROD and Veridica's
 * database of disinformation narratives, searched in memory.
 *
 * It exists because the narratives people bring are mostly old ones coming
 * round again, and the fact-checkers have already answered them — but a live
 * search only finds those answers when its wording happens to line up, and
 * Veridica's database is in no search API at all. Here the whole archive is
 * matched against the claim on every verification, with no network call that
 * could fail or be rate-limited.
 *
 * One operation: `searchFactCheckArchive(query)`. The data file, its compact
 * layout, the Romanian text folding and the ranking all stay in this module.
 * The data is regenerated by scripts/build-factcheck-archive.mjs.
 *
 * A hit means "this fact-check is about similar words", not "this fact-check
 * settles the claim" — the caller still has to check it reviewed the same
 * statement, exactly as for a hit from any other fact-check search.
 */

import archive from './archive.json';

export interface ArchivedFactCheck {
  /** The statement the fact-checker reviewed. */
  claim: string;
  /** The verdict in the publisher's own words ("FALS", "FAKE NEWS", "Trunchiat"). */
  rating: string;
  publisher: string;
  publisherUrl: string;
  url: string;
  /** Review date, YYYY-MM-DD, or '' when the publisher gave none. */
  date: string;
  /** 0-1: how much of the query and of the reviewed statement the two share. */
  relevance: number;
}

/** [claim, rating, index into publishers, url, date] — see the build script. */
type ArchiveEntry = [string, string, number, string, string];

const ENTRIES = archive.entries as ArchiveEntry[];
const PUBLISHERS = archive.publishers;

/** When the archive was last regenerated (YYYY-MM-DD). */
export const FACT_CHECK_ARCHIVE_DATE: string = archive.generatedAt;
export const FACT_CHECK_ARCHIVE_SIZE: number = ENTRIES.length;

/** Words too common in Romanian (and in claims generally) to say what a statement is about. */
const STOPWORDS = new Set(
  (
    'care este sunt fost fiind pentru din dintre intr prin sau dar cum mai ale lui lor unei unui unor ' +
    'aceasta acest acesta aceste acestea fie fara dupa catre asupra despre pana cand unde vor avea are ' +
    'ati fiindca deoarece decat doar inca chiar tot toti toate foarte astfel potrivit spune spus afirma ' +
    'the and that this with from have has was were are for not'
  ).split(' ')
);

/** Lowercase, without diacritics: "Pământul" and "pamantul" must be the same word. */
function fold(text: string): string {
  return text.toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');
}

/**
 * The distinct content words of a text, cut to their first five letters.
 * Romanian inflects at the end of the word ("vaccin", "vaccinul",
 * "vaccinurile"), so the cut makes the forms of a word meet without a
 * stemmer. Numbers are kept whole: "5G" and "2035" identify a claim.
 */
function stems(text: string): Set<string> {
  const out = new Set<string>();
  for (const word of fold(text).split(/[^\p{L}\p{N}]+/u)) {
    if (STOPWORDS.has(word)) continue;
    if (/\d/.test(word)) out.add(word);
    else if (word.length >= 3) out.add(word.slice(0, 5));
  }
  return out;
}

interface SearchIndex {
  /** stem → ids of the entries whose claim contains it */
  postings: Map<string, number[]>;
  /** stem → how rare it is across the archive */
  weight: Map<string, number>;
  /** per entry: the summed weight of all its stems */
  entryWeight: number[];
}

let index: SearchIndex | null = null;

function getIndex(): SearchIndex {
  if (index) return index;

  const postings = new Map<string, number[]>();
  const entryStems = ENTRIES.map(([claim], id) => {
    const set = stems(claim);
    for (const stem of set) {
      const list = postings.get(stem);
      if (list) list.push(id);
      else postings.set(stem, [id]);
    }
    return set;
  });

  const weight = new Map<string, number>();
  for (const [stem, list] of postings) weight.set(stem, Math.log(1 + ENTRIES.length / list.length));

  const entryWeight = entryStems.map((set) => {
    let sum = 0;
    for (const stem of set) sum += weight.get(stem) ?? 0;
    return sum;
  });

  index = { postings, weight, entryWeight };
  return index;
}

/** A word the archive has never seen still counts against the match, as a rare one. */
const UNSEEN_WEIGHT = Math.log(1 + ENTRIES.length);

/** Below this the two statements only share a topic word or two. */
const MIN_RELEVANCE = 0.35;

/**
 * The archived fact-checks whose reviewed statement is closest to the query,
 * best first. Empty when nothing in the archive is about the same thing.
 */
export function searchFactCheckArchive(query: string, limit: number = 6): ArchivedFactCheck[] {
  const queryStems = stems(query);
  if (queryStems.size === 0) return [];

  const { postings, weight, entryWeight } = getIndex();

  let queryWeight = 0;
  const shared = new Map<number, { weight: number; count: number }>();
  for (const stem of queryStems) {
    const w = weight.get(stem) ?? UNSEEN_WEIGHT;
    queryWeight += w;
    for (const id of postings.get(stem) ?? []) {
      const hit = shared.get(id);
      if (hit) {
        hit.weight += w;
        hit.count++;
      } else {
        shared.set(id, { weight: w, count: 1 });
      }
    }
  }

  // A single shared word is a topic, not a statement — unless the query is one word.
  const minShared = Math.min(2, queryStems.size);

  const scored: Array<{ id: number; relevance: number }> = [];
  for (const [id, hit] of shared) {
    if (hit.count < minShared) continue;
    // Both directions matter: a long article-length query must not match every
    // short claim it happens to contain the words of, and a two-word query
    // must not match every long claim that mentions them.
    const ofQuery = hit.weight / queryWeight;
    const ofEntry = hit.weight / entryWeight[id];
    const relevance = (2 * ofQuery * ofEntry) / (ofQuery + ofEntry);
    if (relevance >= MIN_RELEVANCE) scored.push({ id, relevance });
  }

  scored.sort((a, b) => b.relevance - a.relevance || (ENTRIES[a.id][4] < ENTRIES[b.id][4] ? 1 : -1));

  return scored.slice(0, limit).map(({ id, relevance }) => {
    const [claim, rating, publisherIndex, url, date] = ENTRIES[id];
    const publisher = PUBLISHERS[publisherIndex];
    return {
      claim,
      rating,
      publisher: publisher.name,
      publisherUrl: `https://${publisher.site}`,
      url,
      date,
      relevance,
    };
  });
}
