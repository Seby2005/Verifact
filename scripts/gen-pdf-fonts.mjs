// Generates src/lib/pdf/font-data.ts: the PDF fonts embedded as base64 data
// URIs, so the serverless PDF route loads them with no filesystem or network.
// Re-run after changing the fonts in public/fonts.
import { readFileSync, writeFileSync } from 'node:fs';
const FONTS = { interRegular: 'Inter-Regular.ttf', interBold: 'Inter-Bold.ttf', sourceSerif: 'SourceSerif-Regular.ttf' };
let out = '// AUTO-GENERATED by scripts/gen-pdf-fonts.mjs — do not edit by hand.\n';
out += '// PDF report fonts embedded as base64 data URIs (no fs/network at render).\n/* eslint-disable */\n';
for (const [name, file] of Object.entries(FONTS)) {
  const b64 = readFileSync(`public/fonts/${file}`).toString('base64');
  out += `export const ${name} = 'data:font/truetype;base64,${b64}';\n`;
}
writeFileSync('src/lib/pdf/font-data.ts', out);
console.log('wrote src/lib/pdf/font-data.ts —', (out.length/1024).toFixed(0), 'KB');
